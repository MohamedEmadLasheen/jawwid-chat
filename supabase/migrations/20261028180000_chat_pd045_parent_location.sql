-- PD-45 PR-1: a family's country and its state / province / emirate /
-- governorate. Data only: nothing reads or writes the new columns until PR-2.
--
-- Record: docs/product/pd045-parent-location-plan.md (§3.2, §3.3). The owner's
-- request (2026-10-28): "We need to add the country and the
-- state/province/emirate/governorate fields to the registration form, for both
-- new parents and parents who are already registered with us."
--
--   chat.geo_country           every ISO 3166-1 alpha-2 country (plus XK, as
--                              CLDR has it), from CLDR 49. Codes only.
--   chat.geo_subdivision       every FIRST-LEVEL ISO 3166-2 subdivision, under
--                              its country. Codes only: the Arabic and English
--                              names live in apps/api/src/geo/dataset.json, so
--                              the Arabic review (release gate R-45a) never
--                              changes the database.
--   chat.family                + subdivision_code, and who last set the location
--                              (location_source / _updated_at / _updated_by).
--                              The country stays chat.family.country_code.
--   chat.trial_subscription    + country_code, subdivision_code: Sales' form
--                              holds them until PD-16 Assign copies them.
--   chat.contact_location_prompt  who answered the app's one-time "where does
--                              the family live?" (PR-4), so it is never asked
--                              again on another device.
--
-- "The subdivision belongs to the country" is a COMPOSITE foreign key, so no
-- writer -- the API, a legacy path, or SQL -- can store Giza under the UAE.
--
-- The country column gains its own foreign key NOT VALID: the Parent Profile's
-- "other" box and Stories accepted any two letters, so an old row may hold a
-- code that is not a country. New and changed values are checked now; PR-5's
-- backfill lists the old ones for staff to fix, then 20261028190000 validates.
-- A row whose country is not changed is not re-checked, so an old value never
-- blocks an unrelated edit.
--
-- The seed is GENERATED from the pinned CLDR files and the overlay by
-- scripts/geo/build-dataset.py; test/unit/migrations/pd045-parent-location-
-- migration.spec.ts proves it equals the dataset. A later CLDR release is a new
-- migration, which disables the fixed-table triggers for its own changes; a
-- retired code is never deleted (retired_at), so a stored value never dangles.

-- ===========================================================================
-- 1. The reference tables
-- ===========================================================================

create table chat.geo_country (
  code        text primary key check (code ~ '^[A-Z]{2}$'),
  retired_at  timestamptz
);

comment on table chat.geo_country is
  'PD-45: every country a family may live in (ISO 3166-1 alpha-2, from Unicode CLDR 49). Reference data, fixed by its migration. Names are in apps/api/src/geo/dataset.json.';

create table chat.geo_subdivision (
  country_code  text not null references chat.geo_country (code),
  code          text not null check (code ~ '^[A-Z]{2}-[A-Z0-9]{1,3}$'),
  retired_at    timestamptz,
  primary key (country_code, code),
  constraint geo_subdivision_code_in_country check (left(code, 2) = country_code)
);

comment on table chat.geo_subdivision is
  'PD-45: every first-level ISO 3166-2 subdivision (governorate, emirate, province, state), under its country, from Unicode CLDR 49. Reference data, fixed by its migration.';

