#!/usr/bin/env python3
"""PD-45: build the country and subdivision dataset from a pinned CLDR release
and the reviewed overlay (docs/product/pd045-parent-location-plan.md §3.1).

    python3 -I scripts/geo/build-dataset.py --cldr <dir>            # write
    python3 -I scripts/geo/build-dataset.py --cldr <dir> --check    # verify only

<dir> holds the CLDR files at their CLDR paths (common/..., LICENSE), as
scripts/geo/fetch-cldr.sh downloads them. Every input must match its SHA-256 in
data/geo/cldr-49.json, or nothing is written.

Writes, deterministically:
    apps/api/src/geo/dataset.json      codes, Arabic and English names, labels,
                                       the pinned order, every name fallback
    apps/api/src/geo/LICENSE-CLDR.txt  the Unicode License v3 notice
    the GENERATED block of the PD-45 migration: the reference tables' seed,
                                       codes only

The data files are untrusted input: they are parsed as text by fixed patterns,
never executed, and never passed to a shell.
"""
import argparse
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MANIFEST = os.path.join(ROOT, 'data', 'geo', 'cldr-49.json')
OVERLAY = os.path.join(ROOT, 'data', 'geo', 'overlay.json')
DATASET = os.path.join(ROOT, 'apps', 'api', 'src', 'geo', 'dataset.json')
LICENSE = os.path.join(ROOT, 'apps', 'api', 'src', 'geo', 'LICENSE-CLDR.txt')
MIGRATION = os.path.join(ROOT, 'supabase', 'migrations', '20261028180000_chat_pd045_parent_location.sql')
BEGIN = '-- BEGIN GENERATED by scripts/geo/build-dataset.py (codes only; do not edit by hand)'
END = '-- END GENERATED'

# CLDR lists these as regular regions, but ISO 3166-1 only reserves them
# (Ascension, Clipperton, Sark, Diego Garcia, Ceuta and Melilla, the Canary
# Islands, Tristan da Cunha): they are never a family's country. XK (Kosovo)
# stays, as CLDR keeps it.
NOT_COUNTRIES = {'AC', 'CP', 'CQ', 'DG', 'EA', 'IC', 'TA'}
INHERIT = '↑↑↑'  # CLDR's "same as the parent locale" marker: not a name


def sha256(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def expand(token):
    """CLDR validity ranges vary the last character only: 'ag03~8' is ag03..ag08."""
    if '~' not in token:
        return [token]
    first, last = token.split('~')
    if len(last) != 1:
        raise SystemExit(f'geo: unexpected range {token!r}')
    return [first[:-1] + chr(c) for c in range(ord(first[-1]), ord(last) + 1)]


def validity(path, kind):
    """The ids CLDR marks regular in validity/<kind>.xml."""
    m = re.search(r"<id type='%s' idStatus='regular'>(.*?)</id>" % kind, read(path), re.S)
    if not m:
        raise SystemExit(f'geo: no regular {kind} ids in {path}')
    body = re.sub(r'<!--.*?-->', ' ', m.group(1), flags=re.S)
    return {x for tok in body.split() for x in expand(tok)}


def names(path, tag):
    """type -> name, ignoring alt forms and inheritance markers."""
    out = {}
    for m in re.finditer(r'<%s type="([A-Za-z0-9]+)"((?: [a-z]+="[^"]*")*)>([^<]*)</%s>' % (tag, tag), read(path)):
        if 'alt="' in m.group(2):
            continue
        text = m.group(3).strip()
        if text and text != INHERIT:
            out[m.group(1)] = text
    return out


def iso_subdivision(cldr_id):
    """CLDR 'eggz' is ISO 3166-2 'EG-GZ'."""
    return (cldr_id[:2] + '-' + cldr_id[2:]).upper()


def build(cldr):
    manifest = json.loads(read(MANIFEST))
    for rel, want in sorted(manifest['files'].items()):
        path = os.path.join(cldr, rel)
        if not os.path.isfile(path):
            raise SystemExit(f'geo: {rel} is missing from {cldr}')
        got = sha256(path)
        if got != want:
            raise SystemExit(f'geo: {rel} is {got}, the pin is {want}: refusing to build')

    overlay = json.loads(read(OVERLAY))
    c = lambda rel: os.path.join(cldr, rel)
    regions = sorted(r for r in validity(c('common/validity/region.xml'), 'region')
                     if re.fullmatch(r'[A-Z]{2}', r) and r not in NOT_COUNTRIES)
    regular_subs = validity(c('common/validity/subdivision.xml'), 'subdivision')
    top = {m.group(1): m.group(2).split()
           for m in re.finditer(r'<subgroup type="([A-Z]{2})" contains="([^"]*)"', read(c('common/supplemental/subdivisions.xml')))}
    country_names = {'en': names(c('common/main/en.xml'), 'territory'), 'ar': names(c('common/main/ar.xml'), 'territory')}
    sub_names = {'en': names(c('common/subdivisions/en.xml'), 'subdivision'), 'ar': names(c('common/subdivisions/ar.xml'), 'subdivision')}

    for code in list(overlay['countries']) + list(overlay['labels']) + overlay['pinned']:
        if code not in regions:
            raise SystemExit(f'geo: the overlay names {code}, which is not a country in CLDR {manifest["version"]}')

    withheld = set(overlay['arabicWithheld']['codes'])
    fallbacks = []

    def pick(code, found, override):
        """{en, ar} for one code: the overlay, else CLDR, else the other language, else the code."""
        out = {}
        for lang, other in (('en', 'ar'), ('ar', 'en')):
            if override.get(lang):
                out[lang] = override[lang]
            elif found[lang]:
                out[lang] = found[lang]
            elif override.get(other) or found[other]:
                out[lang] = override.get(other) or found[other]
                fallbacks.append(f'{code}:{lang}<-{other}')
            else:
                out[lang] = code
                fallbacks.append(f'{code}:{lang}<-code')
        return out

    used_overrides = set()
    countries = []
    for cc in regions:
        subs = []
        for sid in top.get(cc, []):
            if sid not in regular_subs:
                continue
            code = iso_subdivision(sid)
            if not re.fullmatch(r'[A-Z]{2}-[A-Z0-9]{1,3}', code):
                raise SystemExit(f'geo: {sid} does not map to an ISO 3166-2 code')
            override = overlay['subdivisions'].get(code, {})
            if override:
                used_overrides.add(code)
            if code in withheld:
                withheld.discard(code)
                n = pick(code, {'en': sub_names['en'].get(sid), 'ar': None}, override)
            else:
                n = pick(code, {'en': sub_names['en'].get(sid), 'ar': sub_names['ar'].get(sid)}, override)
            subs.append({'code': code, 'en': n['en'], 'ar': n['ar']})
        subs.sort(key=lambda s: s['code'])
        n = pick(cc, {'en': country_names['en'].get(cc), 'ar': country_names['ar'].get(cc)}, overlay['countries'].get(cc, {}))
        countries.append({'code': cc, 'en': n['en'], 'ar': n['ar'], 'label': overlay['labels'].get(cc), 'subdivisions': subs})

    if withheld:
        raise SystemExit(f'geo: the overlay withholds subdivisions CLDR does not list at first level: {", ".join(sorted(withheld))}')
    unused = sorted(set(overlay['subdivisions']) - used_overrides)
    if unused:
        raise SystemExit(f'geo: the overlay names subdivisions CLDR does not list at first level: {", ".join(unused)}')

    dataset = {
        'version': f'cldr-{manifest["version"]}+overlay-{sha256(OVERLAY)[:12]}',
        'source': {'cldr': manifest['version'], 'tag': manifest['tag'], 'files': manifest['files']},
        'overlaySha256': sha256(OVERLAY),
        'defaultLabel': overlay['defaultLabel'],
        'pinned': overlay['pinned'],
        'fallbacks': sorted(fallbacks),
        'countries': countries,
    }
    return dataset, read(c('LICENSE'))


def dataset_text(d):
    """One subdivision per line: readable, and a CLDR upgrade diffs line by line."""
    j = lambda v: json.dumps(v, ensure_ascii=False)
    lines = ['{']
    for key in ('version', 'source', 'overlaySha256', 'defaultLabel', 'pinned', 'fallbacks'):
        lines.append(f'  {j(key)}: {j(d[key])},')
    lines.append('  "countries": [')
    for i, c in enumerate(d['countries']):
        head = {k: c[k] for k in ('code', 'en', 'ar', 'label')}
        lines.append('    ' + j(head)[:-1] + ', "subdivisions": [')
        for k, s in enumerate(c['subdivisions']):
            lines.append('      ' + j(s) + (',' if k < len(c['subdivisions']) - 1 else ''))
        lines.append('    ]}' + (',' if i < len(d['countries']) - 1 else ''))
    lines.append('  ]')
    lines.append('}')
    text = '\n'.join(lines) + '\n'
    if json.loads(text) != d:
        raise SystemExit('geo: the dataset writer is not lossless')
    return text


def seed_block(d):
    countries = ',\n'.join(f"  ('{c['code']}')" for c in d['countries'])
    subs = ',\n'.join(f"  ('{c['code']}', '{s['code']}')" for c in d['countries'] for s in c['subdivisions'])
    return (f'{BEGIN}\n'
            f"-- {d['version']}: {len(d['countries'])} countries, "
            f"{sum(len(c['subdivisions']) for c in d['countries'])} first-level subdivisions.\n"
            f'insert into chat.geo_country (code) values\n{countries};\n\n'
            f'insert into chat.geo_subdivision (country_code, code) values\n{subs};\n'
            f'{END}')


def with_seed(migration, block):
    begin, end = migration.find(BEGIN), migration.find(END)
    if begin < 0 or end < begin:
        raise SystemExit(f'geo: {MIGRATION} has no GENERATED block to fill')
    return migration[:begin] + block + migration[end + len(END):]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cldr', required=True, help='directory holding the pinned CLDR files at their CLDR paths')
    ap.add_argument('--check', action='store_true', help='verify the committed outputs; write nothing')
    args = ap.parse_args()

    d, license_text = build(os.path.abspath(args.cldr))
    outputs = {DATASET: dataset_text(d), LICENSE: license_text, MIGRATION: with_seed(read(MIGRATION), seed_block(d))}
    stale = [p for p, text in outputs.items() if not os.path.isfile(p) or read(p) != text]
    if args.check:
        for p in stale:
            print(f'geo: {os.path.relpath(p, ROOT)} is not what the pinned inputs build', file=sys.stderr)
        return 1 if stale else 0
    os.makedirs(os.path.dirname(DATASET), exist_ok=True)
    for p in stale:
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write(outputs[p])
    n = sum(len(c['subdivisions']) for c in d['countries'])
    print(f"geo: {d['version']}: {len(d['countries'])} countries, {n} subdivisions, "
          f"{len(d['fallbacks'])} name fallbacks; wrote {len(stale)} file(s)")
    return 0


if __name__ == '__main__':
    sys.exit(main())
