#!/usr/bin/env python3
"""Write the API's map of what may be reviewed (PD-49): apps/api/src/lesson-content/review-subjects.json.

    python3 -I scripts/lessons/lesson-content-subjects.py write      # regenerate it
    python3 -I scripts/lessons/lesson-content-subjects.py check      # CI: fail while it is stale
    python3 -I scripts/lessons/lesson-content-subjects.py selftest

The API cannot read apps/lessons at runtime (its image is built from apps/api
only), so it reviews from this generated copy: every item of each schema-2
content file (scope quran-NNN) and every game mechanic (scope play, from
apps/lessons/src/play/mechanics.json once it exists), each with the SHA-256 of
its canonical JSON and the review steps its kind needs. Both come from
scripts/lessons/check-quran-content.py, the same rules the engine applies.

A signature in the database names an item's hash. Change one letter of an
item, regenerate this file in the same PR (CI insists), and the old signature
no longer describes it: the item waits for review again. The file is written
with ASCII escapes (G-20 scans apps/ for staff names, which can occur inside
ordinary Arabic words).
Standard library only.
"""
import importlib.util
import json
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
QURAN = os.path.join(ROOT, 'apps', 'lessons', 'src', 'content', 'quran')
MECHANICS = os.path.join(ROOT, 'apps', 'lessons', 'src', 'play', 'mechanics.json')
OUT = os.path.join(ROOT, 'apps', 'api', 'src', 'lesson-content', 'review-subjects.json')
ABOUT = ('GENERATED by scripts/lessons/lesson-content-subjects.py from apps/lessons (schema-2 content and game mechanics); '
         'do not edit. CI fails while it is stale (guards.sh lessons-supply-chain).')

_spec = importlib.util.spec_from_file_location('qc', os.path.join(HERE, 'check-quran-content.py'))
qc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(qc)


def subjects_of(items, required):
    return [{'id': it['id'], 'kind': it['kind'], 'itemSha256': qc.item_sha256(it), 'requiredSteps': list(required(it)), 'item': it}
            for it in sorted(items, key=lambda i: i['id'])]


def build(quran_dir=QURAN, mechanics_path=MECHANICS):
    scopes = []
    files = sorted(f for f in os.listdir(quran_dir) if re.fullmatch(r'surah-\d{3}\.json', f)) if os.path.isdir(quran_dir) else []
    for f in files:
        content = json.load(open(os.path.join(quran_dir, f), encoding='utf-8'))
        scopes.append({'scope': f'quran-{int(f[6:9]):03d}', 'subjects': subjects_of(content['items'], qc.required_steps)})
    if os.path.exists(mechanics_path):
        mechanics = json.load(open(mechanics_path, encoding='utf-8'))
        # A mechanic is signed by a teacher and the scholar (plan C.4); it has no source to check.
        scopes.append({'scope': 'play', 'subjects': [
            {'id': m['id'], 'kind': 'mechanic', 'itemSha256': qc.item_sha256(m), 'requiredSteps': ['teacher', 'scholar'], 'item': m}
            for m in sorted(mechanics['mechanics'], key=lambda m: m['id'])]})
    return {'about': ABOUT, 'scopes': scopes}


def render(doc):
    return json.dumps(doc, ensure_ascii=True, indent=1, sort_keys=True) + '\n'


def selftest():
    import tempfile
    failed = []
    with tempfile.TemporaryDirectory() as d:
        os.makedirs(os.path.join(d, 'quran'))
        item = {'id': 'tafsir-001', 'kind': 'tafsir', 'bands': ['6-8'], 'text': 'شرح', 'ayah': 1, 'source': {'work': 'saadi', 'ref': '112:1'}}
        word = {'id': 'word-001', 'kind': 'word', 'bands': ['6-8'], 'text': 'معنى', 'ayah': 1, 'word': 1, 'to': 1, 'source': {'work': 'saadi', 'ref': '112:1'}}
        json.dump({'items': [word, item]}, open(os.path.join(d, 'quran', 'surah-112.json'), 'w', encoding='utf-8'), ensure_ascii=False)
        json.dump({'mechanics': [{'id': 'listen_glow', 'version': 1}]}, open(os.path.join(d, 'mechanics.json'), 'w'))
        doc = build(os.path.join(d, 'quran'), os.path.join(d, 'mechanics.json'))
        scopes = {s['scope']: s for s in doc['scopes']}
        if sorted(scopes) != ['play', 'quran-112']:
            failed.append(f'scopes: {sorted(scopes)}')
        subs = scopes.get('quran-112', {}).get('subjects', [])
        if [s['id'] for s in subs] != ['tafsir-001', 'word-001']:
            failed.append('subjects are not sorted by id')
        if subs and subs[0]['itemSha256'] != qc.item_sha256(item):
            failed.append('itemSha256 is not the canonical hash')
        if subs and (subs[0]['requiredSteps'] != ['check', 'teacher', 'scholar'] or subs[1]['requiredSteps'] != ['check', 'teacher']):
            failed.append(f'required steps: {[s["requiredSteps"] for s in subs]}')
        play = scopes.get('play', {}).get('subjects', [])
        if not play or play[0]['requiredSteps'] != ['teacher', 'scholar']:
            failed.append('a mechanic needs the teacher and the scholar, and no check')
        if re.search('[^\x00-\x7f]', render(doc)):
            failed.append('the file must be ASCII (escaped)')
        empty = build(os.path.join(d, 'none'), os.path.join(d, 'none.json'))
        if empty['scopes'] != []:
            failed.append('no content must give no scopes')
    for f in failed:
        print(f'lesson-content-subjects selftest: FAIL {f}')
    if not failed:
        print('lesson-content-subjects selftest: ids sorted, canonical hashes, required steps, mechanics, ASCII output: each checked')
    return 1 if failed else 0


def main(argv):
    cmd = argv[0] if argv else 'check'
    if cmd == 'selftest':
        return selftest()
    want = render(build())
    if cmd == 'write':
        open(OUT, 'w', encoding='ascii').write(want)
        print(f'lesson-content-subjects: wrote {os.path.relpath(OUT, ROOT)}')
        return 0
    have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if have != want:
        print(f'lesson-content-subjects: {os.path.relpath(OUT, ROOT)} is stale; run: python3 -I scripts/lessons/lesson-content-subjects.py write')
        return 1
    print('lesson-content-subjects: the API reviews exactly the content and mechanics apps/lessons holds')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
