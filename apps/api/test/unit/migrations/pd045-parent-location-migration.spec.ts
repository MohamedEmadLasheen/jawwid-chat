/**
 * PD-45 PR-1: the migration that stores a family's location
 * (docs/product/pd045-parent-location-plan.md §3.2-§3.3), read as text.
 *
 *   - its seed is exactly the dataset's codes (the parity the API relies on:
 *     what the picker offers, the database accepts, and nothing else);
 *   - "the subdivision belongs to the country" is a composite foreign key, on
 *     the family and on Sales' subscription form;
 *   - the existing country column gains its foreign key NOT VALID (old rows
 *     may hold any two letters; PR-5's backfill cleans them, then validates);
 *   - no request role may touch the reference tables or write the new columns;
 *   - Prisma knows every new column.
 *
 * The behaviour is proven against a database in
 * test/integration/pd045-parent-location.spec.ts. Pure: reads files.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const REPO = join(__dirname, '..', '..', '..', '..', '..');
const read = (p: string) => readFileSync(join(REPO, p), 'utf8');
const MIGRATION = 'supabase/migrations/20261028180000_chat_pd045_parent_location.sql';

const sql = read(MIGRATION);
const flat = sql.replace(/--[^\n]*/g, ' ').replace(/\s+/g, ' ').toLowerCase();
const dataset = JSON.parse(read('apps/api/src/geo/dataset.json')) as {
  countries: Array<{ code: string; subdivisions: Array<{ code: string }> }>;
};

function generatedBlock(): string {
  const begin = sql.indexOf('-- BEGIN GENERATED by scripts/geo/build-dataset.py');
  const end = sql.indexOf('-- END GENERATED');
  expect(begin).toBeGreaterThan(-1);
  expect(end).toBeGreaterThan(begin);
  return sql.slice(begin, end);
}

describe('PD-45 migration: the slot', () => {
  it('is the slot the department head assigned', () => {
    const claim = read('docs/product/migration-slots/20261028180000.md');
    expect(claim).toMatch(/^pd: PD-45$/m);
    expect(claim).toMatch(/^migration: chat_pd045_parent_location$/m);
  });
});

describe('PD-45 migration: the seed equals the dataset', () => {
  const block = generatedBlock();

  it('seeds every country of the dataset, and no other', () => {
    const m = block.match(/insert into chat\.geo_country \(code\) values\s*([\s\S]*?);/);
    expect(m).not.toBeNull();
    const seeded = [...m![1]!.matchAll(/\('([A-Z]{2})'\)/g)].map((x) => x[1]);
    expect(seeded).toEqual(dataset.countries.map((c) => c.code));
  });

  it('seeds every subdivision under its country, and no other', () => {
    const m = block.match(/insert into chat\.geo_subdivision \(country_code, code\) values\s*([\s\S]*?);/);
    expect(m).not.toBeNull();
    const seeded = [...m![1]!.matchAll(/\('([A-Z]{2})', '([A-Z]{2}-[A-Z0-9]{1,3})'\)/g)].map((x) => `${x[1]}|${x[2]}`);
    const expected = dataset.countries.flatMap((c) => c.subdivisions.map((s) => `${c.code}|${s.code}`));
    expect(seeded).toEqual(expected);
  });

  it('holds codes only: names live in the dataset, so the Arabic review never changes the database', () => {
    expect(block).not.toMatch(/[؀-ۿ]/);
  });
});

describe('PD-45 migration: the rules', () => {
  it('creates the two reference tables, fixed by their migration', () => {
    expect(flat).toMatch(/create table chat\.geo_country \(\s*code text primary key/);
    expect(flat).toMatch(/create table chat\.geo_subdivision \(/);
    expect(flat).toMatch(/primary key \(country_code, code\)/);
    expect(flat).toMatch(/create trigger geo_country_is_fixed before insert or update or delete or truncate on chat\.geo_country for each statement/);
    expect(flat).toMatch(/create trigger geo_subdivision_is_fixed before insert or update or delete or truncate on chat\.geo_subdivision for each statement/);
  });

  it('adds the family columns: the subdivision and who last set the location', () => {
    for (const col of ['subdivision_code text', 'location_source text', 'location_updated_at timestamptz', 'location_updated_by uuid']) {
      expect(flat).toContain(`alter table chat.family add column ${col}`);
    }
    expect(flat).toMatch(/location_source is null or location_source in \('staff', 'parent', 'backfill'\)/);
  });

  it('makes the subdivision belong to the country, on the family and on Sales\' form', () => {
    expect(flat).toMatch(
      /alter table chat\.family add constraint family_subdivision_in_country foreign key \(country_code, subdivision_code\) references chat\.geo_subdivision \(country_code, code\)/,
    );
    expect(flat).toMatch(
      /alter table chat\.trial_subscription add constraint trial_subscription_subdivision_in_country foreign key \(country_code, subdivision_code\) references chat\.geo_subdivision \(country_code, code\)/,
    );
    expect(flat).toMatch(/family_subdivision_needs_country check \(subdivision_code is null or country_code is not null\)/);
    expect(flat).toMatch(/trial_subscription_subdivision_needs_country check \(subdivision_code is null or country_code is not null\)/);
  });

  it('checks the country against the list: NOT VALID on the family (old rows), at once on Sales\' new columns', () => {
    expect(flat).toMatch(
      /alter table chat\.family add constraint family_country_listed foreign key \(country_code\) references chat\.geo_country \(code\) not valid/,
    );
    expect(flat).toMatch(
      /alter table chat\.trial_subscription add constraint trial_subscription_country_listed foreign key \(country_code\) references chat\.geo_country \(code\)(?! not valid)/,
    );
  });

  it('records who answered the app\'s one-time prompt, once per contact', () => {
    expect(flat).toMatch(/create table chat\.contact_location_prompt \(\s*contact_id uuid primary key references chat\.contact \(id\)/);
    expect(flat).toMatch(/outcome in \('saved', 'later'\)/);
  });

  it('keeps the booking\'s location beside the prospect, never on it (owner 2026-10-29, BR-2)', () => {
    expect(flat).toMatch(/create table chat\.trial_prospect_location \(\s*prospect_id uuid primary key references chat\.trial_prospect \(id\)/);
    expect(flat).toMatch(/country_code text not null constraint trial_prospect_location_country_listed references chat\.geo_country \(code\)/);
    expect(flat).toMatch(
      /constraint trial_prospect_location_subdivision_in_country foreign key \(country_code, subdivision_code\) references chat\.geo_subdivision \(country_code, code\)/,
    );
    expect(flat).toMatch(/create trigger trial_prospect_location_is_coherent before insert or update or delete on chat\.trial_prospect_location for each row execute function chat\.guard_trial_prospect_location\(\)/);
    expect(flat).not.toMatch(/alter table chat\.trial_prospect add/);
  });

  it('grants nothing on the new tables to a request role, and no request role may write the new columns', () => {
    expect(flat).toMatch(
      /revoke all on chat\.geo_country, chat\.geo_subdivision, chat\.contact_location_prompt, chat\.trial_prospect_location from public, anon, authenticated, chat_app/,
    );
    for (const t of ['geo_country', 'geo_subdivision', 'contact_location_prompt', 'trial_prospect_location']) {
      expect(flat).toContain(`alter table chat.${t} enable row level security`);
    }
    expect(flat).not.toMatch(/grant [^;]* to (authenticated|chat_app|anon|public)/);
    expect(flat).toMatch(/a location column is writable by a request role/);
  });
});

describe('PD-45 migration: Prisma', () => {
  const schema = read('apps/api/prisma/schema.prisma');
  const model = (name: string) => {
    const m = schema.match(new RegExp(`model ${name} \\{([\\s\\S]*?)\\n\\}`));
    expect(m).not.toBeNull();
    return m![1]!;
  };

  it('knows the family\'s new columns', () => {
    const family = model('Family');
    expect(family).toMatch(/subdivisionCode\s+String\?\s+@map\("subdivision_code"\)/);
    expect(family).toMatch(/locationSource\s+String\?\s+@map\("location_source"\)/);
    expect(family).toMatch(/locationUpdatedAt\s+DateTime\?\s+@map\("location_updated_at"\) @db\.Timestamptz/);
    expect(family).toMatch(/locationUpdatedBy\s+String\?\s+@map\("location_updated_by"\) @db\.Uuid/);
  });

  it('knows Sales\' form\'s two codes', () => {
    const form = model('TrialSubscription');
    expect(form).toMatch(/countryCode\s+String\?\s+@map\("country_code"\)/);
    expect(form).toMatch(/subdivisionCode\s+String\?\s+@map\("subdivision_code"\)/);
  });

  it('knows the reference tables and the prompt', () => {
    expect(model('GeoCountry')).toMatch(/@@map\("geo_country"\)/);
    expect(model('GeoSubdivision')).toMatch(/@@id\(\[countryCode, code\]\)/);
    expect(model('ContactLocationPrompt')).toMatch(/@@map\("contact_location_prompt"\)/);
    expect(model('TrialProspectLocation')).toMatch(/@@map\("trial_prospect_location"\)/);
    expect(model('TrialProspect')).not.toMatch(/country|subdivision/i);
  });
});
