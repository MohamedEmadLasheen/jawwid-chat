/**
 * PD-40: every route of the API declares what it asks of a staff caller, and
 * the whole map is a reviewed file.
 *
 * Reads the metadata Nest itself routes by -- the controller path, the method
 * path and verb -- and the PD-40 declaration (route-access.ts) or @Public(),
 * on the handler or its class. Fails on:
 *   - a handler with no declaration (PermissionGuard refuses it to staff, so
 *     it would break the moment it shipped);
 *   - a @Requires key that is not in the catalogue;
 *   - docs/security/pd040-route-permissions.md out of date. Every change of
 *     who may reach what shows up in review as a change to that table.
 *     Regenerate with: PD040_WRITE_ROUTE_TABLE=1 npx jest pd040-route-permissions
 *
 * No database, no Nest application: the controllers are only imported.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { RequestMethod } from '@nestjs/common';
import { METHOD_METADATA, PATH_METADATA } from '@nestjs/common/constants';
import { PUBLIC_ROUTE } from '@platform/auth/auth.guard';
import { ROUTE_ACCESS, describeRouteAccess, type RouteAccess } from '@platform/permissions/route-access';
import { PERMISSION_KEYS } from '@platform/permissions/catalogue';

const API = join(__dirname, '..', '..', '..');
const SRC = join(API, 'src');
const TABLE = join(API, '..', '..', 'docs', 'security', 'pd040-route-permissions.md');

interface Route {
  method: string;
  path: string;
  controller: string;
  handler: string;
  access: RouteAccess | undefined;
  isPublic: boolean;
}

function controllerFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return controllerFiles(full);
    return name.endsWith('.controller.ts') ? [full] : [];
  });
}

const join2 = (a: string, b: string) => '/' + [a, b].map((s) => s.replace(/^\/+|\/+$/g, '')).filter(Boolean).join('/');

function collect(): Route[] {
  const routes: Route[] = [];
  for (const file of controllerFiles(SRC)) {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const mod = require(file) as Record<string, unknown>;
    for (const exported of Object.values(mod)) {
      if (typeof exported !== 'function') continue;
      const ctor = exported as { prototype: Record<string, unknown>; name: string };
      const prefix = Reflect.getMetadata(PATH_METADATA, ctor) as string | string[] | undefined;
      if (prefix === undefined) continue;
      const classAccess = Reflect.getMetadata(ROUTE_ACCESS, ctor) as RouteAccess | undefined;
      const classPublic = Reflect.getMetadata(PUBLIC_ROUTE, ctor) === true;
      for (const name of Object.getOwnPropertyNames(ctor.prototype)) {
        if (name === 'constructor') continue;
        const fn = ctor.prototype[name];
        if (typeof fn !== 'function') continue;
        const verb = Reflect.getMetadata(METHOD_METADATA, fn) as RequestMethod | undefined;
        if (verb === undefined) continue;
        const sub = Reflect.getMetadata(PATH_METADATA, fn) as string | string[];
        for (const p of Array.isArray(prefix) ? prefix : [prefix]) {
          for (const s of Array.isArray(sub) ? sub : [sub]) {
            routes.push({
              method: RequestMethod[verb],
              path: join2(p, s),
              controller: `${relative(SRC, file)}#${ctor.name}`,
              handler: name,
              access: (Reflect.getMetadata(ROUTE_ACCESS, fn) as RouteAccess | undefined) ?? classAccess,
              isPublic: Reflect.getMetadata(PUBLIC_ROUTE, fn) === true || classPublic,
            });
          }
        }
      }
    }
  }
  return routes.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

function table(routes: Route[]): string {
  const rows = routes.map(
    (r) => `| ${r.method} | \`/api/v1${r.path}\` | ${r.isPublic ? 'public' : describeRouteAccess(r.access)} | \`${r.controller}.${r.handler}\` |`,
  );
  return [
    '# PD-40 · What every API route asks of a staff caller',
    '',
    'GENERATED by `apps/api/test/unit/authorization/pd040-route-permissions.spec.ts`; do not edit.',
    'Regenerate with `PD040_WRITE_ROUTE_TABLE=1 npx jest pd040-route-permissions` in `apps/api`.',
    '',
    '- `public`: no session at all (login, webhooks, signed media links).',
    '- `self-service`: any signed-in principal, about themself.',
    '- `not for staff`: a parent\'s or a teacher\'s own surface.',
    '- a key list: a staff caller needs one of the keys (`apps/api/src/platform/permissions/catalogue.ts`).',
    '',
    'Only staff callers are checked. The service behind each route still decides department, scope and state.',
    '',
    `${routes.length} routes.`,
    '',
    '| Method | Route | Staff need | Handler |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

const routes = collect();

describe('PD-40: every route declares what it asks of staff', () => {
  it('finds the API (a sanity floor, so an empty walk cannot pass)', () => {
    expect(routes.length).toBeGreaterThanOrEqual(427);
  });

  it('no handler is undeclared, and none is both public and declared', () => {
    const undeclared = routes.filter((r) => !r.isPublic && !r.access).map((r) => `${r.method} ${r.path} (${r.controller}.${r.handler})`);
    expect(undeclared).toEqual([]);
    const both = routes.filter((r) => r.isPublic && r.access).map((r) => `${r.method} ${r.path}`);
    expect(both).toEqual([]);
  });

  it('every key a route requires is in the catalogue', () => {
    const unknown = routes.flatMap((r) => (r.access?.kind === 'requires' ? r.access.anyOf.filter((k) => !PERMISSION_KEYS.has(k)) : []));
    expect(unknown).toEqual([]);
  });

  it('the certificate keys open exactly the certificate routes', () => {
    const opened = (key: string) =>
      routes.filter((r) => r.access?.kind === 'requires' && r.access.anyOf.includes(key as never)).map((r) => `${r.method} ${r.path}`);
    expect(opened('certificates.view')).toEqual(['GET /learner-certificates']);
    expect(opened('certificates.design')).toEqual(['POST /learner-certificates/:id/upload']);
    expect(opened('certificates.deliver').sort()).toEqual(['POST /learner-certificates/:id/decline', 'POST /learner-certificates/:id/issue']);
  });

  it('docs/security/pd040-route-permissions.md is up to date', () => {
    const want = table(routes);
    if (process.env.PD040_WRITE_ROUTE_TABLE === '1') writeFileSync(TABLE, want);
    expect(readFileSync(TABLE, 'utf8')).toBe(want);
  });
});
