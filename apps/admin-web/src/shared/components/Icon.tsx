export type IconName = keyof typeof ICONS

const DIRECTIONAL: ReadonlySet<IconName> = new Set<IconName>([
  'chevronForward',
  'caretLeft',
  'arrowBack',
  'arrowForward',
  'signOut',
  'send',
  'reply',
  'forward',
  'external',
])

/** 1.6 at the usual sizes; a little heavier when an icon is drawn small, so it holds its weight. */
const strokeFor = (size: number) => (size <= 14 ? 1.9 : size <= 16 ? 1.75 : 1.6)

export function Icon({
  name,
  size = 18,
  label,
}: {
  name: IconName
  size?: number
  /** Only for an icon that stands alone with no text beside it. */
  label?: string
}) {
  const Glyph = ICONS[name]
  return (
    <Glyph
      className={DIRECTIONAL.has(name) ? 'icon icon--directional' : 'icon'}
      size={size}
      strokeWidth={strokeFor(size)}
      absoluteStrokeWidth={false}
      aria-hidden={label ? undefined : true}
      role={label ? 'img' : undefined}
      aria-label={label}
      focusable="false"
    />
  )
}
